#include "../includes/libft.h"

char	*ft_strchr(const char *s, int c)
{
	int	i;

	if (!s || *s == '\0')
		return (NULL);
	i = 0;
	while (s[i])
	{
		if ((char)c == s[i])
			return ((char *)&s[i]);
		i++;
	}
	if ((char)c == '\0')
		return ((char *)&s[i]);
	return (NULL);
}
